function project(
  id: string,
  name: string,
  wealthThreshold: number,
  cost: number,
  footprints: LevelSpanTuple,
  levels: Project["levels"],
  description: string,
  stats: Partial<CivElementDef>,
  accentHex: string,
): Project {
  return {
    id,
    name,
    wealthThreshold,
    cost,
    footprints,
    levels,
    description,
    stage: 1,
    category: "wealth_projects",
    archetype: "civic_hall",
    domain: "land",
    needsMaintenance: true,
    ...stats,
    accentHex,
  };
}
