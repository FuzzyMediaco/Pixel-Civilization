export interface CivElementDef {
  id: string;
  name: string;
  category: Exclude<ElementCategory, "starter">;
  isStarter?: boolean;
  wealthThreshold?: number;
  stage: number;
  cost: number;
  archetype: VoxelArchetype;
  domain: PlacementDomain;
  /** Roads, tracks, bridges, rivers, and canals keep 1x1 footprint and auto-connect */
  isNetwork?: boolean;
  /** Whether road traffic & villagers can traverse this network tile */
  isRoadNetwork?: boolean;
  isRailNetwork?: boolean;
  isWaterFeature?: boolean;
  /** Does not require road connection to exist (e.g. trees, hills, water, roads) */
  passiveNature?: boolean;
  /** Base population at Level 1 when connected via road (doubles each level: 1x, 2x, 4x, 8x, 16x) */
  popBase?: number;
  jobs?: number;
  power?: number; // + generates, - consumes
  water?: number; // + supplies, - consumes
  waste?: number; // + processes waste
  food?: number; // + supplies food/groceries
  education?: number;
  recreation?: number;
  government?: number;
  police?: number;
  policeRadius?: number; // in grid tiles
  fireRadius?: number; // in grid tiles
  military?: number;
  nuisanceRadius?: number; // in grid tiles (landfills, coal, factories hurt nearby houses)
  income?: number; // $/tick when connected
  needsMaintenance?: boolean;
  /** Optional starting [spanX, spanZ] footprint at Level 1 (defaults to [1, 1] or stage-tiered) */
  baseSpan?: [number, number];
  /** Optional maximum [spanX, spanZ] footprint across Levels 3..5 (capped at 3x3) */
  maxSpan?: [number, number];
  accentHex: string;
  description: string;
}

